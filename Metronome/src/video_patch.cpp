static uint32_t Rd32(const std::vector<unsigned char>& d, size_t o)
{
    uint32_t v = 0;
    if (o + 4 <= d.size()) memcpy(&v, &d[o], 4);
    return v;
}

static uint16_t Rd16(const std::vector<unsigned char>& d, size_t o)
{
    uint16_t v = 0;
    if (o + 2 <= d.size()) memcpy(&v, &d[o], 2);
    return v;
}

static void Wr16(std::vector<unsigned char>& d, size_t o, uint16_t v)
{
    if (o + 2 <= d.size()) memcpy(&d[o], &v, 2);
}

static void Wr32(std::vector<unsigned char>& d, size_t o, uint32_t v)
{
    if (o + 4 <= d.size()) memcpy(&d[o], &v, 4);
}

static uint32_t AlignUp(uint32_t value, uint32_t align)
{
    return (value + align - 1) / align * align;
}

static bool HasSection(const std::vector<unsigned char>& d, const char* name)
{
    if (d.size() < 0x40 || d[0] != 'M' || d[1] != 'Z') return false;
    size_t pe = Rd32(d, 0x3C);
    if (pe + 24 > d.size()) return false;
    uint16_t nsec = Rd16(d, pe + 6);
    uint16_t optsz = Rd16(d, pe + 20);
    size_t sec = pe + 24 + optsz;
    for (uint16_t i = 0; i < nsec; i++) {
        size_t o = sec + 40 * i;
        if (o + 8 > d.size()) return false;
        if (memcmp(&d[o], name, strlen(name)) == 0) return true;
    }
    return false;
}

static bool AddCave(std::vector<unsigned char>& d)
{
    if (d.size() < 0x40 || d[0] != 'M' || d[1] != 'Z') return false;
    size_t pe = Rd32(d, 0x3C);
    if (pe + 24 > d.size()) return false;
    uint16_t nsec = Rd16(d, pe + 6);
    uint16_t optsz = Rd16(d, pe + 20);
    size_t opt = pe + 24;
    if (opt + 60 > d.size()) return false;

    uint32_t secAlign = Rd32(d, opt + 32);
    uint32_t fileAlign = Rd32(d, opt + 36);
    uint32_t sizeOfImage = Rd32(d, opt + 56);
    if (!secAlign || !fileAlign) return false;
    if (secAlign > 0x10000 || fileAlign > 0x10000) return false;

    uint32_t vaRva = AlignUp(sizeOfImage, secAlign);
    if (vaRva != 0x59000) return false;

    size_t secTable = pe + 24 + optsz;
    if (secTable + 40 * nsec + 40 > d.size()) return false;

    // room for one more header before the first section's raw data
    uint32_t firstRaw = 0xFFFFFFFFu;
    for (uint16_t i = 0; i < nsec; i++) {
        size_t o = secTable + 40 * i;
        uint32_t raw = Rd32(d, o + 20);
        if (raw && raw < firstRaw) firstRaw = raw;
    }
    if (secTable + 40 * nsec + 40 > firstRaw) return false;

    uint32_t blobLen = (uint32_t)sizeof(kBlob);
    uint32_t raw = AlignUp((uint32_t)d.size(), fileAlign);
    uint32_t rawSize = AlignUp(blobLen, fileAlign);
    if (d.size() < raw) d.resize(raw, 0);
    d.insert(d.end(), kBlob, kBlob + blobLen);
    d.resize(raw + rawSize, 0);

    size_t hdr = secTable + 40 * nsec;
    memset(&d[hdr], 0, 40);
    memcpy(&d[hdr], ".tvcave", 7);
    Wr32(d, hdr + 8, blobLen);
    Wr32(d, hdr + 12, vaRva);
    Wr32(d, hdr + 16, rawSize);
    Wr32(d, hdr + 20, raw);
    Wr32(d, hdr + 36, 0x60000020);

    Wr16(d, pe + 6, nsec + 1);
    Wr32(d, opt + 56, vaRva + AlignUp(blobLen, secAlign));
    return true;
}

static bool ReadFile(const char* path, std::vector<unsigned char>& out)
{
    HANDLE f = CreateFileA(path, GENERIC_READ, FILE_SHARE_READ, nullptr,
                           OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (f == INVALID_HANDLE_VALUE) return false;
    LARGE_INTEGER size = {};
    bool ok = GetFileSizeEx(f, &size) && size.QuadPart > 0 &&
              size.QuadPart <= (LONGLONG)0x4000000;
    if (ok) {
        out.resize((size_t)size.QuadPart);
        DWORD read = 0;
        ok = ReadFile(f, out.data(), (DWORD)out.size(), &read, nullptr) &&
             read == out.size();
    }
    CloseHandle(f);
    return ok;
}

static bool WriteFileAll(const char* path, const std::vector<unsigned char>& data)
{
    HANDLE f = CreateFileA(path, GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS,
                           FILE_ATTRIBUTE_NORMAL, nullptr);
    if (f == INVALID_HANDLE_VALUE) return false;
    DWORD written = 0;
    bool ok = WriteFile(f, data.data(), (DWORD)data.size(), &written, nullptr) &&
              written == data.size();
    CloseHandle(f);
    return ok;
}

bool EnsureVideoFix(const char* dllPath, char* status, size_t statusSize)
{
    std::vector<unsigned char> original;
    if (!ReadFile(dllPath, original)) {
        snprintf(status, statusSize, "cutscene fix: cannot read theovorb.dll");
        return false;
    }
    if (HasSection(original, ".tvcave")) {
        snprintf(status, statusSize, "cutscene fix: already installed");
        return true;
    }

    std::vector<unsigned char> patched = original;
    for (const VideoPatch& p : kPatches) {
        size_t off = (size_t)p.va - 0x10000000u - 0xC00u;
        if (off + p.newLen > patched.size()) {
            snprintf(status, statusSize, "cutscene fix: patch site out of range");
            return false;
        }
        if (p.oldLen && memcmp(&patched[off], p.oldBytes, p.oldLen) != 0) {
            snprintf(status, statusSize,
                     "cutscene fix: unknown theovorb.dll (not the known pristine build)");
            return false;
        }
        memcpy(&patched[off], p.newBytes, p.newLen);
    }

    if (!AddCave(patched)) {
        snprintf(status, statusSize, "cutscene fix: unexpected PE layout");
        return false;
    }

    std::string backup = std::string(dllPath) + ".orig";
    if (GetFileAttributesA(backup.c_str()) == INVALID_FILE_ATTRIBUTES)
        WriteFileAll(backup.c_str(), original);

    if (!WriteFileAll(dllPath, patched)) {
        snprintf(status, statusSize, "cutscene fix: cannot write theovorb.dll");
        return false;
    }
    snprintf(status, statusSize, "cutscene fix: installed (backup: theovorb.dll.orig)");
    return true;
}
